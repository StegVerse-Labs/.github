ROOT = Path.cwd().resolve()
RECEIPT_ROOT = (ROOT / "receipts" / "conversation-evidence-ingestion").resolve()
TASK_ID = "CONVERSATION-EVIDENCE-INGESTION-CUSTODY-001"
CAPABILITY = "conversation_evidence_synthetic_ingestion_custody"


def _safe(value: object) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "-", str(value or "")).strip("-") or "unknown"


